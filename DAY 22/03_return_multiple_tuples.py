# Returing multiple tuples
# Basic Tuple
def get_user():
    return "Ali", 18, "Faisalabad"

print(get_user())

# Returning List
def get_coords():
    return [10.2, 34.2, 56.5]

print(get_coords())

# Returning Dictionary
def get_stats():
    return {
        "Company": "hp",
        "Model": "Hp Elitebook 820 g3",
        "Price": 33000
    }

print(get_stats()) 
